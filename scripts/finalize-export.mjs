// Turns `next build` output (out/) into the finished static site, as gulforbit.sa does:
// 1. Arabic is the default locale and lives at the root, so out/ar/** and out/ar.* move up a level.
// 2. config/site-routing.mjs becomes _headers, _redirects (Cloudflare) and .htaccess (Apache).
// 3. Every /_img/<width>/<quality>/<src>.webp URL used by the pages is generated with sharp.
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { siteHeaders, siteRedirects } from "../config/site-routing.mjs";

const OUT = path.resolve("out");
const DEFAULT_LOCALE = "ar";

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

// A file already at dest would mean two routes claim the same URL: fail loudly.
async function moveInto(src, dest) {
  if ((await stat(src)).isDirectory()) {
    await mkdir(dest, { recursive: true });
    for (const name of await readdir(src)) await moveInto(path.join(src, name), path.join(dest, name));
    await rm(src, { recursive: true });
    return;
  }
  if (existsSync(dest)) throw new Error(`refusing to overwrite ${path.relative(OUT, dest)}`);
  await rename(src, dest);
}

async function hoistDefaultLocale() {
  for (const name of await readdir(OUT)) {
    const match = name.match(new RegExp(`^${DEFAULT_LOCALE}(\\..+)$`));
    if (match) await moveInto(path.join(OUT, name), path.join(OUT, `index${match[1]}`));
  }
  const dir = path.join(OUT, DEFAULT_LOCALE);
  if (existsSync(dir)) await moveInto(dir, OUT);
}

const CACHE = "public, max-age=31536000, immutable";
const CACHED = ["/_next/static/", "/_img/", "/icons/", "/fonts/"];

async function writeHostFiles() {
  const [global] = siteHeaders(false);
  const headers = [
    ["/*", ...global.headers.map((h) => `  ${h.key}: ${h.value}`)].join("\n"),
    ...CACHED.map((p) => `${p}*\n  Cache-Control: ${CACHE}`),
  ];
  await writeFile(path.join(OUT, "_headers"), `${headers.join("\n\n")}\n`);

  const redirects = siteRedirects.map((r) => `${r.source} ${r.destination} ${r.permanent ? 308 : 307}`);
  await writeFile(path.join(OUT, "_redirects"), `${redirects.join("\n")}\n`);

  const htaccess = `# Apache / cPanel. Generated by scripts/finalize-export.mjs: do not edit by hand.
Options -MultiViews
DirectorySlash Off
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} off
  RewriteRule ^(.*)$ https://saadjamal.sa/$1 [L,R=301]
  RewriteCond %{HTTP_HOST} ^www\\.saadjamal\\.sa$ [NC]
  RewriteRule ^(.*)$ https://saadjamal.sa/$1 [L,R=301]
${siteRedirects.map((r) => `  RewriteRule ^${r.source.slice(1)}$ ${r.destination} [L,R=301]`).join("\n")}
  # /about/ -> /about (the canonical form)
  RewriteRule ^(.+)/$ /$1 [L,R=301]
  # /about -> about.html
  RewriteCond %{REQUEST_FILENAME}.html -f
  RewriteRule ^(.+)$ $1.html [L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain application/xml application/javascript application/json image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>

<IfModule mod_headers.c>
${global.headers.map((h) => `  Header always set ${h.key} "${h.value}"`).join("\n")}
</IfModule>
`;
  await writeFile(path.join(OUT, ".htaccess"), htaccess);
}

const IMAGE_URL = /\/_img\/(\d+)\/(\d+)(\/[^"'\s,)\\]+)\.webp/g;

async function generateImages() {
  const wanted = new Map();
  for (const file of await walk(OUT)) {
    if (!/\.(html|txt|js)$/.test(file)) continue;
    for (const [url, width, quality, src] of (await readFile(file, "utf8")).matchAll(IMAGE_URL)) {
      wanted.set(url, { width: Number(width), quality: Number(quality), src: decodeURI(src) });
    }
  }
  const jobs = [...wanted.entries()];
  const missing = [];
  let next = 0;
  await Promise.all(
    Array.from({ length: 8 }, async () => {
      while (next < jobs.length) {
        const [url, { width, quality, src }] = jobs[next++];
        const input = path.join(OUT, src);
        if (!existsSync(input)) {
          missing.push(src);
          continue;
        }
        const output = path.join(OUT, decodeURI(url));
        await mkdir(path.dirname(output), { recursive: true });
        await sharp(input).resize({ width, withoutEnlargement: true }).webp({ quality }).toFile(output);
      }
    }),
  );
  if (missing.length) throw new Error(`images referenced but missing: ${[...new Set(missing)].join(", ")}`);
  return jobs.length;
}

await hoistDefaultLocale();
await writeHostFiles();
const images = await generateImages();
console.log(`finalize-export: Arabic hoisted to /, host files written, ${images} responsive images`);
